"""Generates C for the Amiga version's root code (DT1/DuckTales, node 0):
its sound engine (0x544C-0x5E64) and the routines that load its
instruments, for the "Amiga" sound option of the DOS port. Calls into
overlay nodes become calls to amiga_overlay_call() (not used by these).

Usage: sndgen.py <Amiga DuckTales program> <outdir>
Writes amigasnd_gen.c (the functions, with the Amiga runtime names
prefixed so they do not clash with the DOS runtime) and amigasnd_layout.h.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from recomp import FunctionGen, Recompiler, fname, h  # noqa: E402



def main():
    rc = Recompiler(sys.argv[1])
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    funcs = sorted(f for f in rc.an.functions if f[0] == 0)
    code = ['/* Generated by tools/amiga/sndgen.py from the Amiga DuckTales program.', ' * Do not edit. */',
            '#include "amigasnd_rt.h"', '']
    code += [f"void {fname(*f)}(void);" for f in funcs] + [""]
    for f in funcs:
        code.extend(FunctionGen(rc, f[0], f).generate())
    text = "\n".join(code)
    # calls into overlay nodes (not reached by the sound code)
    called = set(re.findall(r"\b(f\d\d_[0-9a-f]{5})\(\)", text)) - {fname(*f) for f in funcs}
    for c in sorted(called):
        text = text.replace(c + "();", f"amiga_overlay_call(0x{c[1:3]}{c[4:]}u);")
    # address -> function, for calls through pointers
    table = ["const AmFunc am_func_table[] = {"]
    table += [f"    {{{h(rc.layout.addr(*f))}, {fname(*f)}}}," for f in funcs]
    table += ["};", f"const int am_func_table_len = {len(funcs)};", ""]
    text += "\n" + "\n".join(table)
    (out / "amigasnd_gen.c").write_text(text)
    lay = rc.layout
    (out / "amigasnd_layout.h").write_text("\n".join([
        "/* Generated by tools/amiga/sndgen.py. */",
        "#ifndef AMIGASND_LAYOUT_H", "#define AMIGASND_LAYOUT_H",
        f"#define AM_NUM_HUNKS {len(lay.base)}",
        f"#define AM_LOAD_END {h(lay.end)}",
        f"#define AM_A4_VALUE {h(lay.base[1] + 0x7FFE)}",
        "static const uint32_t am_hunk_base[AM_NUM_HUNKS] = {",
        "    " + ", ".join(h(lay.base[i]) for i in sorted(lay.base)), "};",
        "#endif", ""]))
    print(f"{len(funcs)} functions")


if __name__ == "__main__":
    main()
